def _slug(task_id: str, platform: str) -> str:
    prefix = f"{platform}."
    value = task_id[len(prefix) :] if task_id.startswith(prefix) else task_id
    value = re.sub(r"[^a-z0-9_-]+", "_", value.lower()).strip("_")
    return value or hashlib.sha256(task_id.encode("utf-8")).hexdigest()[:16]


