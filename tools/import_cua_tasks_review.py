def _source_revision(source_root: Path) -> str | None:
    try:
        completed = subprocess.run(
            ["git", "-C", str(source_root), "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return completed.stdout.strip() or None


def _internal_imports(path: Path) -> set[str]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8-sig"))
    except (OSError, SyntaxError, UnicodeError):
        return set()
    modules: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            modules.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            modules.add(node.module)
    return {name for name in modules if name.split(".", 1)[0] in INTERNAL_IMPORT_ROOTS}


def _missing_internal_imports(repo_root: Path, source_path: Path | None) -> list[str]:
    if source_path is None:
        return []
    missing = []
    for module in sorted(_internal_imports(source_path)):
        if _module_file(repo_root, f"{module}:unused") is None:
            missing.append(module)
    return missing


def _walk_strings(value: Any) -> Iterable[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, Mapping):
        for child in value.values():
            yield from _walk_strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from _walk_strings(child)


def _missing_task_assets(repo_root: Path, task: Mapping[str, Any]) -> list[str]:
    missing: set[str] = set()
    for value in _walk_strings(
        {"init": task.get("init"), "evaluation": task.get("evaluation")}
    ):
        normalized = value.replace("\\", "/").strip()
        if normalized.startswith("tasks/") and not (repo_root / normalized).exists():
            missing.add(normalized)
    return sorted(missing)


def _write_generated(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            return
        if not existing.startswith(GENERATED_COMMENT):
            raise FileExistsError(f"Refusing to overwrite non-generated file: {path}")
    path.write_text(content, encoding="utf-8", newline="\n")


def _restore_release_evaluators(
    benchmark_root: Path, scratch: Path
) -> dict[str, list[Path]]:
    """Rerun the release's evaluator writers on a copy of the release.

    Returns, keyed by artifact path, only the per-task sources that the upload
    lacks; files the release ships are always taken as shipped.
    """

    if not any(benchmark_root.glob(RELEASE_EVALUATOR_WRITERS)):
        return {}
    copy_root = scratch / BENCHMARK_DIR
    shutil.copytree(
        benchmark_root,
        copy_root,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    for writer in sorted(copy_root.glob(RELEASE_EVALUATOR_WRITERS)):
        subprocess.run(
            [sys.executable, str(writer)],
            cwd=copy_root,
            env={**os.environ, "PYTHONPATH": str(copy_root)},
            check=True,
            capture_output=True,
            text=True,
        )
    restored: dict[str, list[Path]] = {}
    for directory in sorted((copy_root / "tasks").glob("*/*/*")):
        shipped = benchmark_root / directory.relative_to(copy_root)
        sources = sorted(directory.glob("*.py"))
        if sources and not any(shipped.glob("*.py")):
            restored[directory.relative_to(copy_root / "tasks").as_posix()] = sources
    return restored


def _build_entries(
    source_root: Path,
    instruction_overrides: Mapping[str, Mapping[str, Any]] | None = None,
    restored_sources: Mapping[str, list[Path]] | None = None,
) -> list[dict[str, Any]]:
    inventory_path = source_root / INVENTORY_NAME
    if not inventory_path.is_file():
        raise FileNotFoundError(f"Missing {INVENTORY_NAME}: {source_root}")
    entries: list[dict[str, Any]] = []
    for line in inventory_path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        app, platform_dir, task_dir = line.split("\t")
        artifact_path = f"{app}/{platform_dir}/{task_dir}"
        directory = source_root / artifact_path
        release_directory = source_root / BENCHMARK_DIR / "tasks" / artifact_path
        use_release = (
            task_dir not in ARTIFACT_ARGS_TASK_DIRS
            and (release_directory / "args.json").is_file()
        )
        args = _read_json((release_directory if use_release else directory) / "args.json")
        task, method = _extract_task(args, directory)
        task_id = str(task.get("task_id") or "").strip().lower()
        override = (instruction_overrides or {}).get(task_id)
        task, original_id = _normalize_task(task, artifact_path, method, override)
        bundled_sources = sorted(release_directory.glob("*.py")) if use_release else []
        bundled_kind = "benchmark"
        if use_release and not bundled_sources:
            bundled_sources = list((restored_sources or {}).get(artifact_path, []))
            bundled_kind = "benchmark_restored"
        if not bundled_sources:
            bundled_sources = _bundled_evaluator_sources(directory)
            bundled_kind = "bundled"
        if use_release:
            task["metadata"]["cua_tasks_review"]["release_path"] = (
                release_directory.relative_to(source_root).as_posix()
            )
        entries.append(
            {
                "app": app,
                "directory": directory,
                "artifact_path": artifact_path,
                "task": task,
                "method": method,
                "original_task_id": original_id,
                "bundled_sources": bundled_sources,
                "bundled_kind": bundled_kind,
            }
        )
    return entries


def _select_evaluator_source(
    entry: Mapping[str, Any],
    module_pool: Mapping[str, list[Path]],
    benchmark_index: Mapping[str, Path],
) -> tuple[Path | None, str | None]:
    evaluation = entry["task"].get("evaluation") or {}
    evaluator_id = str(evaluation.get("evaluator_id") or "")
    if ":" not in evaluator_id:
        return None, None
    module, class_name = evaluator_id.split(":", 1)
    direct = [
        path
        for path in entry["bundled_sources"]
        if _source_declares_class(path, class_name)
    ]
    if direct:
        return direct[0], entry["bundled_kind"]

    indexed = benchmark_index.get(RELEASE_EVALUATOR_MODULES.get(evaluator_id, module))
    if indexed is not None and _source_declares_class(indexed, class_name):
        return indexed, "benchmark_module"

    candidates = [
        path
        for path in module_pool.get(module, [])
        if _source_declares_class(path, class_name)
    ]
    by_hash = {
        hashlib.sha256(path.read_bytes()).hexdigest(): path for path in candidates
    }
    if len(by_hash) == 1:
        return next(iter(by_hash.values())), "shared_module_recovery"
    return None, None


def _version_task_references(task: dict[str, Any], release_manifest: Mapping[str, Any]) -> dict[str, Any]:
    """Relocate live references while retaining historical provenance text."""
    release = release_manifest["release"]
    paths = {
        f"tasks/{item['platform']}/{Path(item['task_path']).name}": item["task_path"]
        for item in release_manifest["tasks"]
        if item["platform"] != "cross_vm"
    }

    def rewrite(value: Any) -> Any:
        if isinstance(value, dict):
            return {key: rewrite(item) for key, item in value.items()}
        if isinstance(value, list):
            return [rewrite(item) for item in value]
        if isinstance(value, str):
            value = paths.get(value, value)
            return re.sub(
                r"tasks/(android|ios|linux|macos|windows)/(files|assets)/",
                rf"tasks/{release}/\1/\2/",
                value,
            )
        return value

    return rewrite(task)


def import_tasks(source_root: Path, repo_root: Path, release: str = "v1") -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="cua-tasks-review-") as scratch:
        restored = _restore_release_evaluators(
            source_root.resolve() / BENCHMARK_DIR, Path(scratch)
        )
        return _import_tasks(source_root, repo_root, release, restored)


def _import_tasks(
    source_root: Path,
    repo_root: Path,
    release: str,
    restored_sources: Mapping[str, list[Path]],
) -> dict[str, Any]:
    source_root = source_root.resolve()
    repo_root = repo_root.resolve()
    if not re.fullmatch(r"v[1-9][0-9]*", release):
        raise ValueError(f"Invalid release: {release!r}")
    task_root = Path("tasks") / release
    release_manifest = _read_json(repo_root / task_root / "manifest.json")
    selected_paths = {
        item["task_id"]: item["task_path"]
        for item in release_manifest["tasks"]
        if item.get("source") == "cua_tasks_review"
    }
    if not selected_paths:
        raise ValueError(f"No reviewed tasks selected for {release}")
    overrides = _instruction_overrides(repo_root, task_root)
    entries = _build_entries(source_root, overrides, restored_sources)
    if len(entries) != 303:
        raise ValueError(f"Expected 303 inventory entries, found {len(entries)}")

    source_ids = {str(entry["task"]["task_id"]) for entry in entries}
    task_id_set = set(selected_paths)
    if not task_id_set <= source_ids:
        raise ValueError(f"Selected tasks missing from source: {sorted(task_id_set - source_ids)}")
    # Briefs for reviewed tasks outside the current selection are kept so a
    # later rebalance can reuse them; every selected task still needs one.
    if overrides and not task_id_set <= set(overrides):
        missing = sorted(task_id_set - set(overrides))
        raise ValueError(f"Instruction override coverage mismatch: missing={missing}")

    task_ids = [entry["task"]["task_id"] for entry in entries]
    duplicates = [task_id for task_id, count in Counter(task_ids).items() if count > 1]
    if duplicates:
        raise ValueError(f"Duplicate normalized task ids: {duplicates}")

    benchmark_root = source_root / BENCHMARK_DIR
    benchmark_index = _benchmark_module_index(benchmark_root)
    vendored_modules: set[str] = set()
    vendored_seen: set[str] = set()
    vendored_files: set[Path] = set()

    module_pool: dict[str, list[Path]] = defaultdict(list)
    for entry in entries:
        evaluator_id = str(
            ((entry["task"].get("evaluation") or {}).get("evaluator_id") or "")
        )
        module = evaluator_id.split(":", 1)[0] if ":" in evaluator_id else ""
        module_pool[module].extend(entry["bundled_sources"])

    manifest_tasks: list[dict[str, Any]] = []
    for entry in entries:
        task = entry["task"]
        if task["task_id"] not in selected_paths:
            continue
        platform = str(task["platform"])
        if platform not in PLATFORM_DIRS:
            raise ValueError(
                f"Unsupported platform {platform!r}: {entry['artifact_path']}"
            )
        task_id = str(task["task_id"])
        slug = _slug(task_id, platform)
        task_rel_path = Path(selected_paths[task_id])
        tracks = {platform} | (WEB_TRACKS if platform == "linux" else set())
        if (
            task_rel_path.parent.parent != task_root
            or task_rel_path.parent.name not in tracks
            or task_rel_path.name != f"{slug}.yaml"
        ):
            raise ValueError(f"Release task path mismatch for {task_id}")
        task = _version_task_references(task, release_manifest)

        evaluation = task.get("evaluation") or {}
        original_evaluator_id = str(evaluation.get("evaluator_id") or "")
        evaluator_source, evaluator_source_kind = _select_evaluator_source(
            entry, module_pool, benchmark_index
        )
        if evaluator_source_kind == "benchmark_module":
            module, class_name = original_evaluator_id.split(":", 1)
            module = RELEASE_EVALUATOR_MODULES.get(original_evaluator_id, module)
            vendored_modules.add(module)
            task["evaluation"]["evaluator_id"] = f"{VENDOR_PACKAGE}.{module}:{class_name}"
        elif evaluator_source is not None and ":" in original_evaluator_id:
            class_name = original_evaluator_id.split(":", 1)[1]
            imported_evaluator_rel = Path("evaluators") / platform / f"{slug}.py"
            imported_module = ".".join(imported_evaluator_rel.with_suffix("").parts)
            task["evaluation"]["evaluator_id"] = f"{imported_module}:{class_name}"
            source_note = (
                f"# Restored evaluator source from {entry['artifact_path']} "
                f"({evaluator_source_kind}).\n"
            )
            source_text = _apply_release_patches(
                original_evaluator_id.split(":", 1)[0],
                evaluator_source.read_text(encoding="utf-8-sig"),
            )
            if evaluator_source_kind and original_evaluator_id.split(":", 1)[0] in RELEASE_SOURCE_PATCHES:
                source_note = source_note.rstrip(".\n") + "; patched, see RELEASE_SOURCE_PATCHES.\n"
            if benchmark_index:
                source_text, dependencies = _vendor_imports(source_text, benchmark_index)
                vendored_modules |= dependencies
            evaluator_text = GENERATED_COMMENT + source_note + source_text
            _write_generated(repo_root / imported_evaluator_rel, evaluator_text)
            _copy_evaluator_sidecars(
                [evaluator_source.parent, entry["directory"]],
                (repo_root / imported_evaluator_rel).parent,
            )
            # Some evaluators verify their own file digest against this param;
            # bind it to the file as written here.
            params = task["evaluation"].get("params")
            if isinstance(params, dict):
                _rebind_evaluator_digests(
                    params, repo_root, imported_module, evaluator_text
                )
        # Initializers OS-Omni does not ship are served from the release, behind
        # the adapter in evaluators/cua_review/core/init_binding.py.
        original_initializer_id = str((task.get("init") or {}).get("initializer_id") or "")
        initializer_module = original_initializer_id.split(":", 1)[0]
        if (
            ":" in original_initializer_id
            and initializer_module in benchmark_index
            and not _declares_class(
                _module_file(repo_root, original_initializer_id), original_initializer_id
            )
        ):
            vendored_modules.add(initializer_module)
            task["init"]["initializer_id"] = f"{VENDOR_PACKAGE}.{original_initializer_id}"
        else:
            original_initializer_id = ""
        vendored_files |= _vendor_benchmark_modules(
            repo_root, benchmark_root, benchmark_index, vendored_modules, vendored_seen
        )

        provenance = task["metadata"]["cua_tasks_review"]
        if original_evaluator_id:
            provenance["original_evaluator_id"] = original_evaluator_id
        if original_initializer_id:
            provenance["original_initializer_id"] = original_initializer_id
        if evaluator_source_kind:
            provenance["evaluator_source"] = evaluator_source_kind

        _write_generated(
            repo_root / task_rel_path, _apply_task_yaml_patches(task_id, _yaml_text(task))
        )

        initializer_id = str(((task.get("init") or {}).get("initializer_id") or ""))
        evaluator_id = str(((task.get("evaluation") or {}).get("evaluator_id") or ""))
        initializer_file = _module_file(repo_root, initializer_id)
        evaluator_file = _module_file(repo_root, evaluator_id)
        unresolved: list[str] = []
        if initializer_id and not _declares_class(initializer_file, initializer_id):
            unresolved.append(f"initializer:{initializer_id or '<missing>'}")
        if not _declares_class(evaluator_file, evaluator_id):
            unresolved.append(f"evaluator:{evaluator_id or '<missing>'}")
        for module in _missing_internal_imports(repo_root, evaluator_file):
            unresolved.append(f"evaluator_import:{module}")
        missing_assets = _missing_task_assets(repo_root, task)
        unresolved.extend(f"asset:{path}" for path in missing_assets)

        manifest_tasks.append(
            {
                "task_id": task_id,
                **(
                    {"original_task_id": entry["original_task_id"]}
                    if entry["original_task_id"]
                    else {}
                ),
                "platform": platform,
                "app": entry["app"],
                "task_path": task_rel_path.as_posix(),
                "artifact_path": entry["artifact_path"],
                "extraction_method": entry["method"],
                "initializer_id": initializer_id,
                "evaluator_id": evaluator_id,
                "original_evaluator_id": original_evaluator_id,
                "evaluator_source": evaluator_source_kind,
                "instruction_summary_source": provenance.get(
                    "instruction_summary_source"
                ),
                "implementation_ready": not unresolved,
                "unresolved": unresolved,
            }
        )

    if benchmark_index:
        _remove_stale_vendored(repo_root, vendored_files)

    method_counts = Counter(item["extraction_method"] for item in manifest_tasks)
    platform_counts = Counter(item["platform"] for item in manifest_tasks)
    instruction_summary_source_counts = Counter(
        item["instruction_summary_source"] for item in manifest_tasks
    )
    unresolved_initializer_tasks = sum(
        any(value.startswith("initializer:") for value in item["unresolved"])
        for item in manifest_tasks
    )
    unresolved_evaluator_tasks = sum(
        any(
            value.startswith("evaluator:") or value.startswith("evaluator_import:")
            for value in item["unresolved"]
        )
        for item in manifest_tasks
    )
    manifest = {
        "schema_version": 1,
        "release": release,
        "source_repository": "Hengyuhan/CUA-Tasks-Review",
        "source_revision": _source_revision(source_root),
        "task_count": len(manifest_tasks),
        "platform_counts": dict(sorted(platform_counts.items())),
        "extraction_counts": dict(sorted(method_counts.items())),
        "instruction_summary_source_counts": dict(
            sorted(instruction_summary_source_counts.items())
        ),
        "implementation_ready_count": sum(
            item["implementation_ready"] for item in manifest_tasks
        ),
        "unresolved_initializer_task_count": unresolved_initializer_tasks,
        "unresolved_evaluator_task_count": unresolved_evaluator_tasks,
        "tasks": sorted(manifest_tasks, key=lambda item: item["task_id"]),
    }
    manifest_path = repo_root / task_root / "cua_tasks_review_manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source_root", type=Path, help="Path to the CUA-Tasks-Review checkout"
    )
    parser.add_argument("--release", default="v1", help="Existing release inventory to regenerate (default: v1)")
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="OS-Omni repository root (defaults to this script's repository)",
    )
    args = parser.parse_args()
    manifest = import_tasks(args.source_root, args.repo_root, args.release)
    print(
        "Imported "
        f"{manifest['task_count']} tasks; "
        f"implementation-ready={manifest['implementation_ready_count']}; "
        f"unresolved-initializer-tasks={manifest['unresolved_initializer_task_count']}; "
        f"unresolved-evaluator-tasks={manifest['unresolved_evaluator_task_count']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
