class LiteralSafeDumper(yaml.SafeDumper):
    """Keep multiline task instructions readable in generated YAML."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _represent_string(dumper: LiteralSafeDumper, value: str) -> yaml.Node:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


LiteralSafeDumper.add_representer(str, _represent_string)


def _read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(value, dict):
        raise ValueError(f"JSON root must be an object: {path}")
    return value


def _instruction_overrides(repo_root: Path, task_root: Path) -> dict[str, Mapping[str, Any]]:
    path = repo_root / task_root / INSTRUCTION_OVERRIDES_NAME
    if not path.is_file():
        return {}
    payload = _read_json(path)
    records = payload.get("instructions")
    if not isinstance(records, dict):
        raise ValueError(f"Missing instruction map in {path}")
    return {
        str(task_id): record
        for task_id, record in records.items()
        if isinstance(record, Mapping)
    }


def _first_text_file(directory: Path, preferred: str | None = None) -> Path:
    if preferred:
        path = directory / preferred
        if path.is_file():
            return path
    candidates = sorted(directory.glob("*.txt"))
    if not candidates:
        raise ValueError(f"No instruction text file found in {directory}")
    return candidates[0]


def _module_file(repo_root: Path, import_id: str) -> Path | None:
    module = str(import_id or "").split(":", 1)[0].strip()
    if not module:
        return None
    file_path = repo_root / (module.replace(".", "/") + ".py")
    if file_path.is_file():
        return file_path
    package_path = repo_root / module.replace(".", "/") / "__init__.py"
    return package_path if package_path.is_file() else None


def _declares_class(path: Path | None, import_id: str, _depth: int = 0) -> bool:
    if path is None or not path.is_file() or ":" not in import_id:
        return False
    module, class_name = import_id.split(":", 1)
    try:
        tree = ast.parse(path.read_text(encoding="utf-8-sig"))
    except (OSError, SyntaxError, UnicodeError):
        return False
    if any(isinstance(node, ast.ClassDef) and node.name == class_name for node in tree.body):
        return True
    # Some release modules only re-export a class declared in a sibling module.
    depth = len(module.split(".")) + (path.name == "__init__.py")
    repo_root = path.parents[depth - 1]
    for node in tree.body:
        if not (isinstance(node, ast.ImportFrom) and node.level == 0 and node.module):
            continue
        for alias in node.names:
            if (alias.asname or alias.name) == class_name and _depth < 3:
                target = f"{node.module}:{alias.name}"
                return _declares_class(_module_file(repo_root, target), target, _depth + 1)
    return False


def _source_declares_class(path: Path, class_name: str) -> bool:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8-sig"))
    except (OSError, SyntaxError, UnicodeError):
        return False
    return any(
        isinstance(node, ast.ClassDef) and node.name == class_name for node in tree.body
    )


def _clean_summary_text(value: Any) -> str:
    """Normalize a metadata summary without changing its task-specific values."""

    text = str(value or "").replace("/n", " ")
    return re.sub(r"\s+", " ", text).strip()


def _task_app_name(task: Mapping[str, Any]) -> str:
    metadata = task.get("metadata")
    metadata = metadata if isinstance(metadata, Mapping) else {}
    for key in ("app_name", "app", "application_name_from_request"):
        value = _clean_summary_text(metadata.get(key))
        if value:
            return value
    task_id = str(task.get("task_id") or "")
    parts = task_id.split(".")
    return parts[1].replace("_", " ") if len(parts) > 1 else "the app"


def _task_subject(task: Mapping[str, Any]) -> str:
    task_id = str(task.get("task_id") or "")
    parts = task_id.split(".")[1:]
    words: list[str] = []
    for part in parts:
        if re.fullmatch(r"\d{6,}", part):
            continue
        words.extend(piece for piece in re.split(r"[_-]+", part) if piece)
    return " ".join(words) or "the requested workflow"


def _ordered_requirements(instruction: str) -> list[str]:
    """Normalize human step formatting without discarding any task content."""

    requirements: list[str] = []
    for raw_line in instruction.replace("\r", "").splitlines():
        line = re.sub(r"^\s*\d+[.)、]\s*", "", raw_line.strip())
        line = re.sub(r"^\s*[-*]\s*", "", line)
        if not line:
            continue
        line = re.sub(r"\s+", " ", line)
        requirements.append(line)
    return requirements


def _rule_summary(rules: Any) -> list[str]:
    """Extract user-facing final outcomes from verifier rules."""

    if isinstance(rules, list):
        values = [item for item in rules if isinstance(item, str)]
    elif isinstance(rules, Mapping):
        values = []
        primary = rules.get("primary_business_evidence")
        if isinstance(primary, list):
            values.extend(item for item in primary if isinstance(item, str))
        checks = rules.get("checks")
        if isinstance(checks, list):
            for check in checks:
                if isinstance(check, Mapping) and isinstance(
                    check.get("evidence"), str
                ):
                    values.append(str(check["evidence"]))
                elif isinstance(check, str):
                    values.append(check)
        for key in ("final_state", "required_outcomes", "requirements"):
            value = rules.get(key)
            if isinstance(value, list):
                values.extend(item for item in value if isinstance(item, str))
            elif isinstance(value, str):
                values.append(value)
    else:
        values = []

    result: list[str] = []
    seen: set[str] = set()
    for value in values:
        text = _clean_summary_text(value)
        if not text:
            continue
        text = re.sub(
            r"^steps?\s+[0-9,\-–]+\s+require\s+(?:the\s+)?",
            "",
            text,
            flags=re.IGNORECASE,
        )
        text = re.sub(
            r"^steps?\s+[0-9,\-–]+\s+(?:deliver|produce)\s+",
            "",
            text,
            flags=re.IGNORECASE,
        )
        if re.match(
            r"^(final foreground app must|data source|trajectory|flow[-_ ]only|forbidden assumptions?)",
            text,
            re.IGNORECASE,
        ):
            continue
        lower = text.lower()
        if any(
            marker in lower
            for marker in (
                "read /api/",
                "foreground accessibility",
                "flow-only",
                "auxiliary evidence",
                "evaluator check",
                "benchmark events",
                "not final-page evidence",
                "trajectory.jsonl",
                "initializer baseline",
                "host-side initializer",
                "full runs require",
                "evaluator reads",
                "required api events",
            )
        ):
            continue
        if text not in seen:
            result.append(text.rstrip("."))
            seen.add(text)
    return result


def _append_model_constraints(task: Mapping[str, Any], summary: str) -> str:
    """Carry over only high-value account/interaction constraints."""

    instruction = str(task.get("instruction") or "")
    lowered = instruction.lower()
    constraints: list[str] = []
    if re.search(
        r"(do not|don't|never|不要|禁止).{0,40}(sign out|log out|退出登录|登出|退出账号)",
        lowered,
    ):
        constraints.append("Do not sign out or exit the account.")
    if re.search(
        r"(only visible|仅通过|只通过).{0,50}(gui|gui controls|图形界面)", lowered
    ):
        constraints.append("Use visible GUI actions only.")
    if re.search(r"(do not|不要).{0,30}(click start|点击 start)", lowered):
        constraints.append("Do not click Start.")
    existing = summary.lower()
    additions = [item for item in constraints if item.lower() not in existing]
    return f"{summary} {' '.join(additions)}".strip()


def _model_instruction(task: Mapping[str, Any]) -> str:
    """Create a concise goal plus complete ordered requirements for the model."""

    metadata = task.get("metadata")
    metadata = metadata if isinstance(metadata, Mapping) else {}
    app = _task_app_name(task)
    subject = _task_subject(task)
    description = _clean_summary_text(metadata.get("description"))
    if description:
        goal = description
    else:
        evidence = _rule_summary(metadata.get("verifier_rules"))
        if evidence:
            goal_evidence = "; ".join(evidence[:4])
            goal = (
                f"Complete the {app} workflow for {subject}. Final-state targets: "
                f"{goal_evidence}."
            )
        else:
            goal = f"Complete the {app} workflow for {subject}."

    requirements = _ordered_requirements(str(task.get("instruction") or ""))
    if requirements:
        requirement_blocks = [
            "; ".join(requirements[index : index + 8])
            for index in range(0, len(requirements), 8)
        ]
        details = "\n".join(f"- {block}" for block in requirement_blocks)
        return _append_model_constraints(
            task, f"Goal: {goal}\n\nComplete these requirements in order:\n{details}"
        )
    return _append_model_constraints(
        task, f"Goal: {goal}\n\nLeave the evaluated final state ready for verification."
    )


def _replace_instruction_with_summary(
    task: dict[str, Any], instruction_override: Mapping[str, Any] | None = None
) -> None:
    original = str(task.get("instruction") or "")
    source_hash = hashlib.sha256(original.encode("utf-8")).hexdigest()
    if instruction_override is not None:
        if instruction_override.get("source_instruction_sha256") != source_hash:
            raise ValueError(f"Stale instruction override for {task.get('task_id')}")
        summary = str(instruction_override.get("instruction") or "").strip()
        if not summary:
            raise ValueError(f"Empty instruction override for {task.get('task_id')}")
    else:
        summary = _model_instruction(task)
    task["instruction"] = summary
    metadata = task.get("metadata")
    if not isinstance(metadata, dict):
        metadata = {}
        task["metadata"] = metadata
    provenance = metadata.get("cua_tasks_review")
    if not isinstance(provenance, dict):
        provenance = {}
        metadata["cua_tasks_review"] = provenance
    if instruction_override is not None and instruction_override.get("preserve_original_instruction") is True:
        if summary != original.strip():
            raise ValueError(f"Original instruction override changed the workflow for {task.get('task_id')}")
        provenance["instruction_format"] = "original_numbered_workflow"
        provenance["instruction_summary_source"] = "preserved_source_instruction"
    elif instruction_override is not None:
        provenance["instruction_format"] = "english_natural_language"
        provenance["instruction_summary_source"] = "generated_english_natural_language"
    elif _clean_summary_text(metadata.get("description")):
        provenance["instruction_format"] = "model_summary"
        provenance["instruction_summary_source"] = "metadata.description"
    elif metadata.get("verifier_rules"):
        provenance["instruction_format"] = "model_summary"
        provenance["instruction_summary_source"] = "verifier_rules"
    else:
        provenance["instruction_format"] = "model_summary"
        provenance["instruction_summary_source"] = "compressed_workflow"
    provenance["source_instruction_sha256"] = source_hash
    # Evaluators bind to the instruction they were written against; the runners
    # hand them this text (core.evaluation.context), so evaluation params keep
    # the source digests while metadata describes the brief the model sees.
    provenance["source_instruction"] = original
    new_hash = hashlib.sha256(summary.encode("utf-8")).hexdigest()
    for key in _HASH_FIELDS:
        if key in metadata:
            metadata[key] = new_hash


